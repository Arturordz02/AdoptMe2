-- 1. Creación de la tabla Solicitudes
CREATE TABLE IF NOT EXISTS "Solicitudes" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "MascotaId" integer NOT NULL,
    "AdoptanteId" integer NOT NULL,
    "PetName" character varying(100) NOT NULL,
    "PetSpecies" character varying(50) NOT NULL DEFAULT '',
    "ApplicantName" character varying(150) NOT NULL,
    "Phone" character varying(20) NOT NULL,
    "Email" character varying(200) NOT NULL,
    "Address" character varying(250) NOT NULL,
    "HousingType" character varying(100) NOT NULL,
    "TimeAvailability" character varying(100) NOT NULL DEFAULT '',
    "PreviousExperience" character varying(150) NOT NULL DEFAULT '',
    "Reason" character varying(2000) NOT NULL,
    "Status" character varying(30) NOT NULL DEFAULT 'Pendiente',
    "Observacion" character varying(1000),
    "FechaSolicitud" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "FechaActualizacion" timestamp with time zone,
    CONSTRAINT "PK_Solicitudes" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Solicitudes_Mascotas_MascotaId" FOREIGN KEY ("MascotaId") 
        REFERENCES "Mascotas" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Solicitudes_Usuarios_AdoptanteId" FOREIGN KEY ("AdoptanteId") 
        REFERENCES "Usuarios" ("Id") ON DELETE RESTRICT
);

-- 2. Índices de optimización para consultas frecuentes
CREATE INDEX IF NOT EXISTS "IX_Solicitudes_MascotaId" ON "Solicitudes" ("MascotaId");
CREATE INDEX IF NOT EXISTS "IX_Solicitudes_AdoptanteId" ON "Solicitudes" ("AdoptanteId");
CREATE INDEX IF NOT EXISTS "IX_Solicitudes_Status" ON "Solicitudes" ("Status");

